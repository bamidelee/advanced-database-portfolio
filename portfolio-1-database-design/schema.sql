-- =====================================================================
-- AquaFlow Water Tanker Services - PostgreSQL Schema
-- MIT 8103 Advanced Database Systems - Portfolio 1
--
-- Run with:  psql -U postgres -d aquaflow -f schema.sql
-- The script is re-runnable: it drops existing objects first and runs
-- inside a single transaction, so a failure leaves nothing half-built.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- Clean slate (reverse dependency order)
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS rating, vendor_earning, payout, refund, payment,
  trip_status_history, trip, job_offer, delivery_request, tanker, driver,
  vendor, address, customer, pricing_rule, service_area, staff CASCADE;

DROP TYPE IF EXISTS customer_type, verification_status, tanker_status,
  request_status, offer_response, trip_status, payment_method,
  payment_status, payout_status, staff_role CASCADE;

-- ---------------------------------------------------------------------
-- Enumerated types
-- ---------------------------------------------------------------------
CREATE TYPE customer_type       AS ENUM ('household', 'business');
CREATE TYPE verification_status AS ENUM ('pending', 'verified', 'suspended');
CREATE TYPE tanker_status       AS ENUM ('available', 'busy', 'offline', 'maintenance');
CREATE TYPE request_status      AS ENUM ('pending', 'assigned', 'completed', 'cancelled');
CREATE TYPE offer_response      AS ENUM ('pending', 'accepted', 'declined', 'expired');
CREATE TYPE trip_status         AS ENUM ('assigned', 'en_route', 'arrived', 'completed', 'failed', 'cancelled');
CREATE TYPE payment_method      AS ENUM ('card', 'bank_transfer');
CREATE TYPE payment_status      AS ENUM ('pending', 'successful', 'failed', 'reversed');
CREATE TYPE payout_status       AS ENUM ('pending', 'paid', 'failed');
CREATE TYPE staff_role          AS ENUM ('operations', 'finance', 'admin');

-- ---------------------------------------------------------------------
-- Staff (created first: referenced by pricing, vendors, refunds, payouts)
-- ---------------------------------------------------------------------
CREATE TABLE staff (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name   varchar(150) NOT NULL,
  email       varchar(255) NOT NULL UNIQUE,
  role        staff_role   NOT NULL,
  is_active   boolean      NOT NULL DEFAULT true
);

-- ---------------------------------------------------------------------
-- Locations and pricing
-- ---------------------------------------------------------------------
CREATE TABLE service_area (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        varchar(100) NOT NULL UNIQUE,
  is_active   boolean      NOT NULL DEFAULT true
);

CREATE TABLE pricing_rule (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_area_id        bigint        NOT NULL REFERENCES service_area (id),
  price_per_1000_litres  numeric(12,2) NOT NULL,
  effective_from         timestamptz   NOT NULL,
  created_by             bigint        NOT NULL REFERENCES staff (id),

  CONSTRAINT uq_pricing_rule_area_start UNIQUE (service_area_id, effective_from),
  CONSTRAINT chk_pricing_rule_price_positive CHECK (price_per_1000_litres > 0)
);

-- ---------------------------------------------------------------------
-- Customers
-- ---------------------------------------------------------------------
CREATE TABLE customer (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name      varchar(150)  NOT NULL,
  phone          varchar(20)   NOT NULL UNIQUE,
  email          varchar(255)  UNIQUE,
  customer_type  customer_type NOT NULL DEFAULT 'household',
  created_at     timestamptz   NOT NULL DEFAULT now()
);

CREATE TABLE address (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id           bigint       NOT NULL REFERENCES customer (id),
  service_area_id       bigint       NOT NULL REFERENCES service_area (id),
  label                 varchar(50),
  street_address        varchar(255) NOT NULL,
  latitude              numeric(9,6) NOT NULL,
  longitude             numeric(9,6) NOT NULL,
  tank_capacity_litres  integer,
  contact_name          varchar(150) NOT NULL,
  contact_phone         varchar(20)  NOT NULL,
  access_notes          text,

  -- Target of the composite foreign key from delivery_request
  CONSTRAINT uq_address_id_customer UNIQUE (id, customer_id),
  CONSTRAINT chk_address_tank_capacity_positive CHECK (tank_capacity_litres > 0),
  CONSTRAINT chk_address_coordinates
    CHECK (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
);

-- ---------------------------------------------------------------------
-- Vendors and fleet
-- ---------------------------------------------------------------------
CREATE TABLE vendor (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_name        varchar(150)        NOT NULL,
  owner_name           varchar(150)        NOT NULL,
  phone                varchar(20)         NOT NULL UNIQUE,
  bank_name            varchar(100)        NOT NULL,
  account_number       varchar(20)         NOT NULL,
  verification_status  verification_status NOT NULL DEFAULT 'pending',
  verified_by          bigint              REFERENCES staff (id),
  created_at           timestamptz         NOT NULL DEFAULT now(),

  -- A verified vendor must record which staff member verified them
  CONSTRAINT chk_vendor_verified_by
    CHECK (verification_status <> 'verified' OR verified_by IS NOT NULL)
);

CREATE TABLE driver (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id       bigint       NOT NULL REFERENCES vendor (id),
  full_name       varchar(150) NOT NULL,
  phone           varchar(20)  NOT NULL UNIQUE,
  licence_number  varchar(50)  NOT NULL UNIQUE,
  is_active       boolean      NOT NULL DEFAULT true
);

CREATE TABLE tanker (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id        bigint        NOT NULL REFERENCES vendor (id),
  plate_number     varchar(20)   NOT NULL UNIQUE,
  capacity_litres  integer       NOT NULL,
  status           tanker_status NOT NULL DEFAULT 'offline',

  CONSTRAINT chk_tanker_capacity_positive CHECK (capacity_litres > 0)
);

-- ---------------------------------------------------------------------
-- Requests, offers and trips
-- ---------------------------------------------------------------------
CREATE TABLE delivery_request (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id    bigint         NOT NULL REFERENCES customer (id),
  address_id     bigint         NOT NULL,
  volume_litres  integer        NOT NULL,
  scheduled_for  timestamptz,   -- NULL means immediate delivery
  quoted_price   numeric(12,2)  NOT NULL, -- price snapshot at request time
  status         request_status NOT NULL DEFAULT 'pending',
  created_at     timestamptz    NOT NULL DEFAULT now(),

  -- The address must belong to the same customer who made the request
  CONSTRAINT fk_request_address_belongs_to_customer
    FOREIGN KEY (address_id, customer_id) REFERENCES address (id, customer_id),
  CONSTRAINT chk_request_volume_positive CHECK (volume_litres > 0),
  CONSTRAINT chk_request_price_positive  CHECK (quoted_price > 0)
);

CREATE TABLE job_offer (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id    bigint         NOT NULL REFERENCES delivery_request (id),
  tanker_id     bigint         NOT NULL REFERENCES tanker (id),
  offered_at    timestamptz    NOT NULL DEFAULT now(),
  responded_at  timestamptz,
  response      offer_response NOT NULL DEFAULT 'pending',

  -- A tanker is offered a given request at most once
  CONSTRAINT uq_job_offer_request_tanker UNIQUE (request_id, tanker_id),
  -- A response other than pending must record when it was given
  CONSTRAINT chk_job_offer_responded_at
    CHECK (response = 'pending' OR responded_at IS NOT NULL)
);

CREATE TABLE trip (
  id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id               bigint      NOT NULL REFERENCES delivery_request (id),
  offer_id                 bigint      NOT NULL UNIQUE REFERENCES job_offer (id),
  tanker_id                bigint      NOT NULL REFERENCES tanker (id),
  driver_id                bigint      NOT NULL REFERENCES driver (id),
  status                   trip_status NOT NULL DEFAULT 'assigned',
  volume_delivered_litres  integer,
  failure_reason           text,
  assigned_at              timestamptz NOT NULL DEFAULT now(),
  completed_at             timestamptz,

  CONSTRAINT chk_trip_volume_positive CHECK (volume_delivered_litres > 0),
  -- A failed trip must say why it failed
  CONSTRAINT chk_trip_failure_reason
    CHECK (status <> 'failed' OR failure_reason IS NOT NULL),
  -- A completed trip must record when it finished and how much was delivered
  CONSTRAINT chk_trip_completion_details
    CHECK (status <> 'completed'
           OR (completed_at IS NOT NULL AND volume_delivered_litres IS NOT NULL))
);

-- At most one active or completed trip per request.
-- Failed and cancelled trips are excluded, so a request can be retried.
-- Also blocks two vendors being assigned the same request concurrently.
CREATE UNIQUE INDEX one_live_trip_per_request
  ON trip (request_id)
  WHERE status NOT IN ('failed', 'cancelled');

CREATE TABLE trip_status_history (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id     bigint      NOT NULL REFERENCES trip (id),
  status      trip_status NOT NULL,
  changed_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Money
-- ---------------------------------------------------------------------
CREATE TABLE payment (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id         bigint         NOT NULL UNIQUE REFERENCES delivery_request (id),
  amount             numeric(12,2)  NOT NULL,
  method             payment_method NOT NULL,
  gateway_reference  varchar(100)   NOT NULL UNIQUE,
  status             payment_status NOT NULL DEFAULT 'pending',
  paid_at            timestamptz,

  CONSTRAINT chk_payment_amount_positive CHECK (amount > 0),
  -- A successful payment must record when it was paid
  CONSTRAINT chk_payment_paid_at
    CHECK (status <> 'successful' OR paid_at IS NOT NULL)
);

CREATE TABLE refund (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id   bigint        NOT NULL REFERENCES payment (id),
  amount       numeric(12,2) NOT NULL,
  reason       text          NOT NULL,
  approved_by  bigint        NOT NULL REFERENCES staff (id),
  refunded_at  timestamptz   NOT NULL DEFAULT now(),

  CONSTRAINT chk_refund_amount_positive CHECK (amount > 0)
);

CREATE TABLE payout (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id     bigint        NOT NULL REFERENCES vendor (id),
  total_amount  numeric(12,2) NOT NULL,
  status        payout_status NOT NULL DEFAULT 'pending',
  processed_by  bigint        REFERENCES staff (id),
  paid_at       timestamptz,

  CONSTRAINT chk_payout_amount_positive CHECK (total_amount > 0),
  -- A paid payout must record who released it and when
  CONSTRAINT chk_payout_paid_details
    CHECK (status <> 'paid' OR (processed_by IS NOT NULL AND paid_at IS NOT NULL))
);

CREATE TABLE vendor_earning (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id            bigint        NOT NULL UNIQUE REFERENCES trip (id),
  vendor_id          bigint        NOT NULL REFERENCES vendor (id), -- snapshot of owner at trip time
  gross_amount       numeric(12,2) NOT NULL,
  commission_amount  numeric(12,2) NOT NULL,
  net_amount         numeric(12,2) GENERATED ALWAYS AS (gross_amount - commission_amount) STORED,
  payout_id          bigint        REFERENCES payout (id), -- NULL until paid out

  CONSTRAINT chk_earning_amounts
    CHECK (gross_amount > 0 AND commission_amount >= 0 AND commission_amount <= gross_amount)
);

CREATE TABLE rating (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id     bigint      NOT NULL UNIQUE REFERENCES trip (id),
  score       smallint    NOT NULL,
  comment     text,
  created_at  timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT chk_rating_score_range CHECK (score BETWEEN 1 AND 5)
);

-- ---------------------------------------------------------------------
-- Documentation stored in the database catalogue
-- ---------------------------------------------------------------------
COMMENT ON COLUMN delivery_request.quoted_price IS
  'Price quoted at request time. Stored deliberately so later pricing changes do not alter historical requests.';
COMMENT ON COLUMN vendor_earning.vendor_id IS
  'Tanker owner at the time of the trip. Stored deliberately so earnings stay with the original owner if a tanker changes hands.';
COMMENT ON INDEX one_live_trip_per_request IS
  'At most one active or completed trip per request; failed and cancelled trips may repeat.';

-- Note: no performance indexes on foreign key columns yet.
-- PostgreSQL does not create them automatically. They are added in
-- Portfolio 2 with before/after execution plans as evidence.

COMMIT;